# Data Types: Booleans

# === Basics ===
# Booleans can be 2 values, True or False
human = True
print(human)
print(type(human))  # <class 'bool'>

# === Combining Bools and Strings ===
#print("Are you a human: " + human)  # Error!
# We can fix this with type casting!
print("Are you a human: " + str(human))

