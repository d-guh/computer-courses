# Values, Variables, and Data

# Value = an instance of some data
# Variable = an object that refers to a value
# Data = the information itself

# Example
age = 25
# `age` is a variable referring to the value 25 (integer). The value 25 is some data.
# Most commonly we'll use variable and value when referring to this.

age = 26
# You can reassign a variable with different values, that is new data, but still the same variable name.

